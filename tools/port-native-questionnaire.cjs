// Deterministic native definitions from the reviewed reference inventory.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const inventory=JSON.parse(fs.readFileSync(path.join(root,'planning/docs/schemas/questionnaire-current.json'),'utf8'));
const q=s=>JSON.stringify(s).replaceAll('$','\\$');
const types={text:'Text',textarea:'TextArea',tel:'Phone',number:'Number',date:'Date','datetime-local':'DateTime',choice:'Choice',select:'Select',multi:'MultiSelect',photo:'Photo'};
function condition(source){
 if(!source)return null;
 const expression=source.replace(/^a=>/,'');
 const terms=expression.split('&&').map(term=>{
  let m=term.match(/^a\.(\w+)==='([^']*)'$/);
  if(m)return `Condition.Equals(${q(m[1])}, ${q(m[2])})`;
  m=term.match(/^!!a\.(\w+)$/);
  if(m)return `Condition.Answered(${q(m[1])})`;
  throw Error('Unmapped condition: '+source);
 });
 return terms.length===1?terms[0]:`Condition.All(listOf(${terms.join(', ')}))`;
}
const lines=['package ph.tala.registry.domain.form','','import ph.tala.registry.domain.model.*','','/** Generated by tools/port-native-questionnaire.cjs; demo labels and current scope retained. */','object QuestionnaireSections {','    const val VERSION = "tala-demo-v1"'];
for(const s of inventory.sections){
 const fields=s.fields.filter(f=>!['head','name'].includes(f.key));
 // Native member pictures are attachments, not serialized questionnaire answers.
 if(s.route==='demographics')fields.push({key:'photo',label:'Member Profile Picture (Optional)',type:'photo',optional:true});
 if(s.route==='consent')fields.push({key:'consent',label:'Agrees to the fictional-data demo interview?',type:'choice',options:['Yes','No']},{key:'signedName',label:'Typed fictional signature',type:'text',condition:"a=>a.consent==='Yes'"});
 lines.push(`    val ${s.route} = SectionSpec(${q(s.route)}, ${q(s.title)}, listOf(`);
 for(const f of fields){
  const args=[q(f.key),q(f.label),`FieldType.${types[f.type]}`];
  if(f.options?.length)args.push(`options = listOf(${f.options.map(q).join(', ')})`);
  if(f.optional)args.push('optional = true');
  if(f.hint)args.push('hint = '+q(f.hint));
  if(f.min!==undefined)args.push('min = '+f.min);
  if(f.max!==undefined)args.push('max = '+f.max);
  if(f.past)args.push('mustBePast = true');
  if(f.condition)args.push('visibleWhen = '+condition(f.condition));
  const exclusive=(f.options||[]).filter(x=>['None','Prefer not to answer'].includes(x));
  if(f.type==='multi'&&exclusive.length)args.push(`exclusiveOptions = setOf(${exclusive.map(q).join(', ')})`);
  lines.push('        FieldSpec('+args.join(', ')+'),');
 }
 lines.push(`    ), scopedToMember = ${s.scope==='member'})`);
}
lines.push(`    val all = listOf(${inventory.sections.map(s=>s.route).join(', ')})`,'    val forms = all.filter { it.fields.isNotEmpty() }','    fun get(route: String) = all.single { it.route == route }','}');
const target=path.join(root,'android-native/app/src/main/java/ph/tala/registry/domain/form/QuestionnaireSections.kt');
const generated=lines.join('\n')+'\n';
if(process.argv.includes('--check')) {
 if(fs.readFileSync(target,'utf8').replaceAll('\r\n','\n')!==generated) throw Error('Native questionnaire differs from the planning inventory.');
 console.log('Verified all 18 native section definitions against the planning inventory.');
} else {
 fs.writeFileSync(target,generated);
 console.log('Generated 18 native section definitions; current demo scope retained.');
}
